function odSvg(name, size) {
  const inner = OD_ICONS[name] || OD_ICONS['hash'];
  const s = size || 18;
  return `<svg xmlns="http://www.w3.org/2000/svg" width="${s}" height="${s}" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true">${inner}</svg>`;
}

/* <i data-icon="name" data-size="16"></i> → 内联 SVG */
function odHydrateIcons(root) {
  (root || document).querySelectorAll('[data-icon]').forEach((el) => {
    el.outerHTML = odSvg(el.dataset.icon, el.dataset.size ? +el.dataset.size : 18);
  });
}

/* 主题：与线上项目共用 localStorage 键 zhe-theme */
function odTheme() { return document.documentElement.dataset.theme === 'dark' ? 'dark' : 'light'; }
function odSetTheme(t) {
  document.documentElement.dataset.theme = t;
  try { localStorage.setItem('zhe-theme', t); } catch (e) { /* 隐私模式静默 */ }
  document.querySelectorAll('[data-theme-toggle]').forEach((btn) => {
    btn.innerHTML = odSvg(t === 'dark' ? 'sun' : 'moon', 18);
    btn.setAttribute('aria-label', t === 'dark' ? '切换到浅色模式' : '切换到深色模式');
  });
}

document.addEventListener('DOMContentLoaded', () => {
  odHydrateIcons();
  document.querySelectorAll('[data-theme-toggle]').forEach((btn) => {
    btn.addEventListener('click', () => odSetTheme(odTheme() === 'dark' ? 'light' : 'dark'));
  });
  odSetTheme(odTheme());
});

/* 复制到剪贴板（带反馈） */
async function odCopy(text, tipEl) {
  try {
    await navigator.clipboard.writeText(text);
    if (tipEl) { tipEl.textContent = '已复制到剪贴板'; setTimeout(() => { tipEl.textContent = ''; }, 1600); }
  } catch (e) {
    if (tipEl) tipEl.textContent = '复制失败，请手动选择复制';
  }
}
